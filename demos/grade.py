# Program to calculate & print grade
# A => >= 80 
# B => >= 60
# C => >= 40
# D => < 40
percent = 35

if percent >= 80:
    print("Congrats!, You grade is A")
elif percent >= 60:
    print("Congrats!, You grade is B")
elif percent >= 40:
    print("Congrats!, You grade is C")
else:
    print("Your grade is D")

