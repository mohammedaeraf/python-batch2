# Algorithm for Program to calculate Area of a Rectangle
# Step 1 - Read len and breadth
# Step 2 - Calculate area = len * breadth
# Step 3 - Output area

input1 = input("Enter the length:")
length = int(input1)

input2 = input("Enter the breadth:")
breadth = int(input2)

area = length * breadth
print("Area =", area)